// Stage-0 bundler (2026-11-20). Text-level on purpose: the source is copied verbatim (comments, one-line CFG entries and
// line layout stay exactly as written), unlike esbuild which drops/moves comments and reformats objects.
//   node build/build.js            builds dist/*.js
// A line  // @include relative/path.js  inside a source file is replaced by that file's text (used from stage 1 on).
// Each output gets (1) a header comment and (2) a first-line runtime banner that writes the build id to the game log.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src");
const DIST = path.join(ROOT, "dist");
const VERSION = "v6";
const TARGETS = [
  { src: "entries/AutoMerchant.js", out: "AutoMerchant " + VERSION + ".js", label: "AutoMerchant", tag: "Merchant" },
  { src: "entries/AutoRanger.js", out: "AutoRanger " + VERSION + ".js", label: "AutoRanger", tag: "Ranger" },
  { src: "entries/AutoWarrior.js", out: "AutoWarrior " + VERSION + ".js", label: "AutoWarrior", tag: "Warrior" },
  { src: "entries/AutoPriest.js", out: "AutoPriest " + VERSION + ".js", label: "AutoPriest", tag: "Priest" },
  { src: "lib/index.js", out: "AL Libs " + VERSION + ".js", label: "AL Libs (code slot \"lib\")", tag: "Lib" },
];
const included = new Set();
function read_with_includes(rel, base, trail) {
  const file = path.join(base, rel);
  if (trail.includes(file)) throw new Error("include cycle: " + trail.concat(file).join(" -> "));
  const text = fs.readFileSync(file, "utf8");
  return text.split("\n").map((line) => {
    const m = line.match(/^\s*\/\/ @include (\S+)\s*$/);
    if (!m) return line;
    const inc = path.join(path.dirname(file), m[1]);
    included.add(path.relative(SRC, inc).replace(/\\/g, "/"));
    return read_with_includes(path.relative(path.dirname(file), inc), path.dirname(file), trail.concat(file));
  }).join("\n");
}
const built = TARGETS.map((t) => {
  included.clear();
  const body = read_with_includes(path.basename(t.src), path.join(SRC, path.dirname(t.src)), []);
  return { t, body, modules: [t.src].concat([...included]) };
});
// one build id for the whole set: a hash over every target's source text, so four characters that print the same id run the same build
const build_id = crypto.createHash("sha1").update(built.map((b) => b.t.out + "\n" + b.body).join("\n--\n")).digest("hex").slice(0, 8);
const stamp = new Date().toISOString().slice(0, 16).replace("T", " ") + "Z";
fs.mkdirSync(DIST, { recursive: true });
for (const b of built) {
  const mods = b.modules.join(", ");
  const header = "// " + b.t.label + " " + VERSION + " | build " + build_id + " | built " + stamp + " | sources: " + mods + "\n// GENERATED by build/build.js from src/ - edit src/, not this file.\n";
  // runtime banner (one line, before everything else): the same build id must show on all four characters and the lib slot
  const banner = 'try { game_log("[build] ' + b.t.tag + " " + VERSION + " build " + build_id + " | " + mods.replace(/"/g, "") + '", "#7DC4E4"); } catch (e) {}\n';
  fs.writeFileSync(path.join(DIST, b.t.out), header + banner + b.body);
  console.log("built dist/" + b.t.out + "  (" + (header.length + banner.length + b.body.length) + " bytes)");
}
console.log("build id " + build_id);
