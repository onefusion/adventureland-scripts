// Static checks on the build output (run after `node build/build.js`):  node tests/build_check.js
//  - every dist file starts with the header comment and the runtime banner line (build id the same in all files)
//  - the dist body is the source text verbatim (stage 0: no @include yet, so dist = header + banner + src)
//  - rebuilding without a source change gives the same build id (deterministic)
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const ROOT = path.resolve(__dirname, "..");
const read = (...p) => fs.readFileSync(path.join(ROOT, ...p), "utf8");
// the source text with every "// @include file" line replaced by that file's text (the same rule as build/build.js)
const expand = (rel) => read("src", rel).split("\n").map((l) => { const m = l.match(/^\s*\/\/ @include (\S+)\s*$/); return m ? expand(path.join(path.dirname(rel), m[1])) : l; }).join("\n");
const pairs = [["entries/AutoMerchant.js", "AutoMerchant v6.js"], ["entries/AutoRanger.js", "AutoRanger v6.js"], ["entries/AutoWarrior.js", "AutoWarrior v6.js"], ["entries/AutoPriest.js", "AutoPriest v6.js"], ["lib/index.js", "AL Libs v6.js"]];
let bad = 0;
const check = (ok, label) => { if (!ok) bad++; console.log((ok ? "ok   " : "FAIL ") + label); };
const ids = new Set();
for (const [s, d] of pairs) {
  const out = read("dist", d), lines = out.split("\n");
  const m = lines[0].match(/^\/\/ .* v6 \| build ([0-9a-f]{8}) \| built .* \| sources: /);
  check(!!m, d + ": header comment with build id");
  if (m) ids.add(m[1]);
  check(/^try \{ game_log\("\[build\] \w+ v6 build [0-9a-f]{8} \| /.test(lines[2]), d + ": runtime banner is the first statement");
  check(lines[1].startsWith("// GENERATED by build/build.js"), d + ": generated-file notice");
  check(lines.slice(3).join("\n") === expand(s), d + ": body equals src/" + s + " (includes expanded) verbatim");
}
check(ids.size === 1, "one build id across all files (" + [...ids].join(",") + ")");
const before = [...ids][0];
const after = execFileSync("node", [path.join(ROOT, "build", "build.js")], { encoding: "utf8" }).match(/build id ([0-9a-f]{8})/)[1];
check(before === after, "rebuild is deterministic (" + before + " -> " + after + ")");
console.log(bad ? bad + " check(s) failed" : "build checks passed");
process.exit(bad ? 1 : 0);
